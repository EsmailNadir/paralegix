/**
 * A mechanical inventory of every HTTP endpoint the Express app actually
 * registers, with each mount prefix resolved to a fully qualified path.
 *
 * WHAT IT IS FOR
 *
 * Route SHAPE is the one property of this API that nothing else records. The
 * router files are spread across seventy-odd modules, several are mounted in
 * groups on one `app.use` line, three share a generated notes surface, and the
 * files module resolves its permissions through a lookup map instead of route
 * middleware. That makes "what endpoints exist" a question no single file
 * answers, which in turn makes "is every endpoint covered by an authorization
 * test" unanswerable. This catalog is that missing denominator: a test can walk
 * it, and a route added without a matching expectation shows up as a gap
 * instead of shipping unexamined.
 *
 * HOW IT WAS DERIVED
 *
 * Every `.ts` file under `src/` was parsed with the TypeScript compiler API and
 * searched for `router.get/post/put/patch/delete` and `app.use` calls. The
 * `app.use` lines in `src/app.ts` gave the prefix for each router file, and
 * nested prefixes were resolved on top of those:
 *
 *   - the three notes surfaces are expanded from `createNotesRouter`
 *     (`src/shared/notes/notesRouter.ts`), fourteen routes for each of the
 *     matter, task and client mounts, with that mount's permission map applied;
 *   - the files module is composed of four sub-routers behind
 *     `files.storage.routes.ts`, and its permissions come from the
 *     `routePermissions` map in `files.routes.ts` that `enforceFilesPermission`
 *     reads, since those routes carry no `requirePermission` of their own;
 *   - routers that authenticate once with `router.use` (admin, portal, stripe,
 *     subscriptions) have that gate attributed to each of their routes.
 *
 * `permissions` and `featureGate` report what the middleware SAYS, read off the
 * call sites. Nothing here is inferred from what a route appears to do.
 *
 * WARNING: THIS FILE IS NOT AN AUTHORIZATION EXPECTATION
 *
 * The `permissions`, `featureGate` and `authCategory` columns are a transcript
 * of the middleware that is wired up today, not a statement of what each route
 * OUGHT to require. Do not build expected-authorization assertions by reading
 * them back out of this file. Deriving the expectation from the same middleware
 * that implements it means a permission wired to the wrong code, or a route
 * that lost its gate entirely, would be compared against itself and pass. What
 * a route should require has to be authored independently, by a person deciding
 * it from the resource being touched, and then compared against this catalog.
 * Use this file for the SET of routes and their shapes; author the expectations
 * elsewhere.
 */

export type RouteMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';

/**
 * How a caller is admitted to the route, as the middleware states it.
 *
 * - `firm-member`: `verifyToken`, in the firm workspace. A handful of these
 *   admit any authenticated Firebase user rather than a firm member (account
 *   self-service under `/api/users` and `/api/auth`, invitation acceptance);
 *   those carry a `note`.
 * - `portal-client`: `verifyToken` plus `requireUserType(['client'])`.
 * - `public-token`: unauthenticated, addressed by a capability token in the URL.
 * - `cron`: `authorizeCronRequest` (CRON_SECRET).
 * - `webhook`: provider callback, verified inside the handler.
 * - `platform-admin`: `requireIsAdmin`.
 * - `anonymous`: no auth middleware at all.
 * - `docs-session`: the two endpoints that mint and clear the docs cookie.
 */
export type AuthCategory =
  | 'firm-member'
  | 'portal-client'
  | 'public-token'
  | 'cron'
  | 'webhook'
  | 'platform-admin'
  | 'anonymous'
  | 'docs-session';

/** The resource whose id scopes the path, read off the path parameters. */
export type ParentType =
  | 'lawfirm'
  | 'matter'
  | 'task'
  | 'client'
  | 'user'
  | 'token'
  | 'platform'
  | 'none';

export interface RouteRow {
  method: RouteMethod;
  /** Fully mounted path, every app.use and nested router prefix resolved. */
  path: string;
  authCategory: AuthCategory;
  parentType: ParentType;
  /**
   * Permission codes the route's middleware names. A `requirePermission([a, b])`
   * call is any-of and a route with two `requirePermission` calls is all-of;
   * both flatten to the codes listed here, so read the source before treating
   * this as a conjunction.
   */
  permissions: readonly string[];
  /** Plan feature gate (`requireFeature`) applied to the route, if any. */
  featureGate: string | null;
  /** Path, relative to `backend/`, of the file the route is registered in. */
  sourceFile: string;
  /** Line of the registration call in `sourceFile`. */
  sourceLine: number;
  /** Anything about the wiring a reader would otherwise have to go find. */
  note?: string;
}


/**
 * Assembles backend/db/schema.sql from the modular domain files in backend/db/schema/*.sql.
 *
 * Usage:
 *   npx tsx backend/db/build-schema.ts          # Regenerate schema.sql
 *   npx tsx backend/db/build-schema.ts --check  # Verify schema.sql is up to date (CI check)
 */

import fs from 'node:fs';
import path from 'node:path';

const DB_DIR = __dirname;
const SCHEMA_DIR = path.join(DB_DIR, 'schema');
const OUTPUT_FILE = path.join(DB_DIR, 'schema.sql');

export function buildSchemaSql(): string {
  if (!fs.existsSync(SCHEMA_DIR)) {
    throw new Error(`Schema directory not found: ${SCHEMA_DIR}`);
  }

  const files = fs.readdirSync(SCHEMA_DIR)
    .filter((f) => f.endsWith('.sql'))
    .sort();

  if (files.length === 0) {
    throw new Error(`No .sql files found in: ${SCHEMA_DIR}`);
  }

  const header = `-- =====================================================================
-- Paralegix - Postgres schema
-- Source of truth: backend/db/schema/*.sql
-- Generated by:    npm run db:schema:build
-- Apply with:      npx tsx backend/db/apply-schema.ts
-- Idempotent-ish:  uses IF NOT EXISTS where possible.
-- =====================================================================\n\n`;

  const body = files.map((file) => {
    const fullPath = path.join(SCHEMA_DIR, file);
    const content = fs.readFileSync(fullPath, 'utf8').trim();
    return `-- >>> ${file} <<<\n${content}`;
  }).join('\n\n');

  return `${header}${body}\n`;
}

export function checkSchemaSql(): boolean {
  const generated = buildSchemaSql();
  const current = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, 'utf8') : '';
  return generated === current;
}

if (require.main === module) {
  const isCheck = process.argv.includes('--check');
  if (isCheck) {
    if (!checkSchemaSql()) {
      console.error('[build-schema] FAIL: backend/db/schema.sql is out of date with backend/db/schema/*.sql.');
      console.error('Run: npm run db:schema:build');
      process.exit(1);
    }
    console.log('[build-schema] OK: backend/db/schema.sql is in sync with backend/db/schema/*.sql.');
  } else {
    const content = buildSchemaSql();
    fs.writeFileSync(OUTPUT_FILE, content, 'utf8');
    console.log(`[build-schema] OK: assembled ${OUTPUT_FILE} (${content.length} bytes).`);
  }
}

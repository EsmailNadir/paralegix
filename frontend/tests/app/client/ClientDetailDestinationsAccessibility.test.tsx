jest.unmock('@/services/client-portal.service');
jest.unmock('@/services/lawfirm.service');
jest.unmock('@/services/requestDeduplicator');
jest.mock('@/lib/utils/sanitizeHtml', () => ({ sanitizeRichHtml: (value: string) => value }));
const mockUser = { uid: 'test-uid' };
const mockNavigate = jest.fn();
jest.mock('@/hooks/useAuth', () => ({ useAuth: () => ({ user: mockUser }) }));
jest.mock('next/navigation', () => ({ useParams: () => ({ lawFirmId: 'firm-a', matterId: 'matter-a' }), useSearchParams: () => new URLSearchParams() }));
jest.mock('@/contexts/NavigationContext', () => ({ useNavigation: () => ({ navigate: mockNavigate }) }));
jest.mock('@/contexts/ClientPortalContext', () => ({ useClientPortal: () => ({ associations: [], associationsLoading: false, activeAssociation: { clientRecordId: 'record-a' }, selectionRequired: false }) }));
import React from 'react';
import { screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import Detail from '@/app/client/lawfirm/[lawFirmId]/matters/[matterId]/page';
import Firm from '@/app/client/lawfirm/[lawFirmId]/page';
import { renderWithProviders } from '../../support/renderWithProviders';
import { setupApiMock } from '../../support/apiMock';
const api = setupApiMock();
it('provides actual document and invoice destinations from the loaded matter', async () => {
  api.get('/matters/matter-a', { matter: { id: 'matter-a', title: 'Estate Planning', status: 'active' } });
  api.get('/events', { events: [], truncated: false });
  api.get('/billing', { invoices: [{ id: 'invoice-a', matterId: 'matter-a', totalAmount: 100, amountPaid: 0 }] });
  api.get('/matters/matter-a/documents', { documents: [{ id: 'doc-a', matterId: 'matter-a', name: 'Agreement.pdf', type: 'application/pdf', size: 100, uploadedAt: '2026-10-04T12:00:00Z', downloadUrl: '', objectPath: 'docs/a.pdf' }], truncated: false });
  api.get('/document-requests', { requests: [] });
  renderWithProviders(<Detail />);
  await screen.findByRole('heading', { level: 1, name: 'Estate Planning' });
  const documents = screen.getByRole('link', { name: 'View all documents' });
  expect(documents).toHaveAttribute('href', '/client/lawfirm/firm-a/documents?matter=matter-a');
  const invoices = screen.getByRole('link', { name: 'View & pay invoices' });
  expect(invoices).toHaveAttribute('href', '/client/lawfirm/firm-a/billing');
  documents.focus();
  await userEvent.keyboard('{Enter}');
  expect(mockNavigate).toHaveBeenCalledWith('/client/lawfirm/firm-a/documents?matter=matter-a');
  expect(api.callsTo('/matters/matter-a')[0].url).toContain('clientRecordId=record-a');
});
it('provides named native matter and message destinations on the firm overview', async () => {
  api.getExact('/api/lawfirms/firm-a', { lawFirm: { id: 'firm-a', name: 'Firm A' } });
  api.get('/matters', { matters: [{ id: 'matter-a', title: 'Estate Planning', status: 'active' }] });
  renderWithProviders(<Firm />);
  const matter = await screen.findByRole('link', { name: /Estate Planning/ });
  expect(matter).toHaveAttribute('href', '/client/lawfirm/firm-a/matters/matter-a');
  const messages = screen.getByRole('link', { name: 'Message Law Firm' });
  expect(messages).toHaveAttribute('href', '/client/messages/firm-a');
  messages.focus();
  await userEvent.keyboard('{Enter}');
  expect(mockNavigate).toHaveBeenCalledWith('/client/messages/firm-a');
});

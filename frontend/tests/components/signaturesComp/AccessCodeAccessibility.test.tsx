jest.unmock('@/services/signatures.service');
jest.unmock('@/services/requestDeduplicator');
import React from 'react';
import { screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import AccessCodeGate from '@/components/signaturesComp/AccessCodeGate';
import { renderWithProviders } from '../../support/renderWithProviders';
import { setupApiMock, sequence } from '../../support/apiMock';
const api = setupApiMock();
it('associates a refused code and lets the keyboard signer correct it without changing the token', async () => {
  api.post('/signing/token-a/verify-access-code', sequence({ status: 403, body: { attemptsRemaining: 2 } }, { verified: true }));
  const onVerified = jest.fn();
  const user = userEvent.setup();
  renderWithProviders(<AccessCodeGate token="token-a" onVerified={onVerified} />);
  const code = screen.getByRole('textbox', { name: 'Access code' });
  await user.type(code, 'wrong{Enter}');
  expect(await screen.findByRole('alert')).toHaveTextContent('2 attempts remaining');
  await waitFor(() => expect(code).toHaveFocus());
  expect(code).toHaveAttribute('aria-invalid', 'true');
  expect(code).toHaveAccessibleDescription(/Incorrect access code.*2 attempts remaining/);
  await user.type(code, 'correct{Enter}');
  await waitFor(() => expect(onVerified).toHaveBeenCalledTimes(1));
  expect(api.calls('POST').map(call => call.body)).toEqual([{ code: 'wrong' }, { code: 'correct' }]);
});
it('focuses transport failures and locked feedback while keeping the countdown out of live announcements', async () => {
  api.post('/signing/token-a/verify-access-code', sequence({ status: 503, body: { error: 'Verification unavailable' } }, { status: 429, body: { lockedSeconds: 1 } }));
  const user = userEvent.setup();
  renderWithProviders(<AccessCodeGate token="token-a" onVerified={jest.fn()} />);
  const code = screen.getByRole('textbox', { name: 'Access code' });
  await user.type(code, 'sample{Enter}');
  let alert = await screen.findByRole('alert');
  expect(alert).toHaveFocus();
  expect(code).not.toHaveAttribute('aria-invalid', 'true');
  await user.click(screen.getByRole('button', { name: 'Verify' }));
  alert = await screen.findByRole('alert');
  await waitFor(() => expect(alert).toHaveTextContent('Too many failed attempts'));
  expect(alert).toHaveFocus();
  expect(code).toBeDisabled();
  expect(screen.getByText(/Try again in/).closest('[role="status"], [aria-live]')).toBeNull();
  await waitFor(() => expect(code).toBeEnabled(), { timeout: 2000 });
  expect(code).toHaveFocus();
});
